#!/usr/bin/env python3
"""Validate UI catalogs and generate the shared offline browser bundle."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def bundle():
    catalogs = {p.stem: json.loads(p.read_text(encoding='utf-8')) for p in sorted((ROOT / 'web/locales').glob('*.json'))}
    english = catalogs['en']
    if any(key != value for key, value in english.items()):
        raise ValueError('English catalog values must equal their source message keys')
    for locale, messages in catalogs.items():
        if messages.keys() != english.keys():
            raise ValueError(f'{locale}: catalog keys differ from English')
        for key, value in messages.items():
            if sorted(re.findall(r'\{\d+\}', key)) != sorted(re.findall(r'\{\d+\}', value)):
                raise ValueError(f'{locale}: interpolation mismatch for {key!r}')
            # Translated templates retain the exact static HTML structure.
            if re.findall(r'<[^>]*>', key) != re.findall(r'<[^>]*>', value):
                # Accessible text and placeholders may be translated inside attributes.
                clean = lambda s: re.sub(r'(aria-label|placeholder)="[^"]*"', r'\1=""', s)
                if re.findall(r'<[^>]*>', clean(key)) != re.findall(r'<[^>]*>', clean(value)):
                    raise ValueError(f'{locale}: HTML structure mismatch for {key!r}')
    return '// Generated by scripts/sync-i18n.py; edit the JSON catalogs.\n' + 'globalThis.HP_MESSAGES = ' + json.dumps(catalogs, ensure_ascii=True, indent=2) + ';\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if the generated bundle is stale')
    args = parser.parse_args()
    path = ROOT / 'web/locales/catalogs.js'
    content = bundle()
    if args.check:
        if not path.exists() or path.read_text(encoding='utf-8') != content:
            raise SystemExit('Run python3 scripts/sync-i18n.py to update the catalog bundle')
    else:
        path.write_bytes(content.encode('utf-8'))
    print('UI catalogs validated')


if __name__ == '__main__':
    main()
