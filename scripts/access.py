#!/usr/bin/env python3
"""Show initial deployment credentials locally; never serve them over the web API."""
import argparse
import json
import os
from pathlib import Path


def read_env(path):
    values = {}
    for line in path.read_text(encoding='utf-8').splitlines():
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        key, separator, value = line.partition('=')
        if not separator:
            raise ValueError(f'Invalid environment entry in {path}')
        # setup.py emits literal, unquoted values. Never execute/source the file.
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        values[key] = value
    return values


def access_text(env, location, hide_secrets=False, ready=True):
    local = env.get('HP_BIND', '127.0.0.1:3000')
    domain = env.get('HP_PANEL_DOMAIN', '')
    https_port = env.get('HP_HTTPS_LISTEN', ':443').rsplit(':', 1)[-1]
    public_url = f'https://{domain}' + (f':{https_port}' if https_port != '443' else '') if domain else None
    host = env.get('HP_PUBLIC_ADDR', 'SERVER_IP:2333').rsplit(':', 1)[0]
    secret = lambda key: '[hidden; read the protected configuration file]' if hide_secrets else env.get(key, '[not configured]')
    rows = ['HolePunch is ready.' if ready else 'HolePunch installation is prepared. Start the stack before opening the panel.',
            '', 'Open your browser to manage HolePunch:',
            f'  Management URL: {public_url or "http://127.0.0.1:" + local.rsplit(":",1)[-1]}',
            f'  Local listener: http://{local}']
    if not domain:
        port = local.rsplit(':', 1)[-1]
        rows += ['  No public panel domain is configured. From your own computer, run:',
                 f'  ssh -L {port}:{local} YOUR_SSH_USER@{host}',
                 '  Then open the management URL on that computer.']
    elif https_port != '443':
        rows += ['  If an upstream edge forwards public 443 to this HTTPS listener, use the domain without this port.']
    rows += ['', 'Initial administrator credentials:',
             f'  Email: {env.get("HP_BOOTSTRAP_EMAIL", "[not configured]")}',
             f'  Password: {secret("HP_BOOTSTRAP_PASSWORD")}',
             f'  Administrator API token: {secret("HP_ADMIN_TOKEN")}',
             f'  Protected configuration: {location}', '',
             'Sign in to open the first-run Setup guide. Choose Language in the page header.',
             'The API token is for server administration, not web sign-in or client enrollment.',
             'Create each client in the console to get its own one-time enrollment code.',
             'These are bootstrap credentials; a password changed in the console is not updated here.',
             'Keep this summary private. Use --hide-secrets when collecting deployment logs.']
    return '\n'.join(rows) + '\n'


def save_summary(path, env, location):
    # Refuse symlinks/overwrites; retries continue to use the existing protected summary.
    try:
        fd = os.open(path, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    except FileExistsError:
        return
    with os.fdopen(fd, 'w', encoding='utf-8') as output:
        output.write(access_text(env, location, ready=False))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sources = parser.add_mutually_exclusive_group(required=True)
    sources.add_argument('--config', type=Path, help='Native PREFIX/config.json')
    sources.add_argument('--env-file', type=Path, help='Compose .env generated by setup.py')
    parser.add_argument('--hide-secrets', action='store_true')
    args = parser.parse_args()
    path = args.config or args.env_file
    env = json.loads(path.read_text())['env'] if args.config else read_env(path)
    # Reading a file alone cannot establish service readiness.
    print(access_text(env, path, args.hide_secrets, ready=False), end='')


if __name__ == '__main__':
    main()
